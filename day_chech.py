
number_of_days = int(input("Enter a number: "))

if number_of_days % 7 == 0:
    print('Sunday')

if  number_of_days % 7 == 1:
    print('Monday')

if  number_of_days % 7 == 2:
    print('Tuesday')

if  number_of_days % 7 == 3:
    print('Wednesday')

if  number_of_days % 7 == 4:
    print('Thursday')

if  number_of_days % 7 == 5:
    print('Friday')

if  number_of_days % 7 == 6:
    print('Saturday')
